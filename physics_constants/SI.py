qe_SI = 1.602176634e-19  # Кл
G_SI = 6.67430e-11  # м³/(кг·с²)

print(f"  Задано: l_P = {lP_SI:.6e} м")
print()

# Шкала перевода: натуральная l_P → физическая
# l_P_физ = λ · l_P_нат
# λ = l_P_SI / l_P_nat

lambda_len = lP_SI / lP_nat  # м/натед.длины
print(f"  l_P (натур.) = {lP_nat:.6e}  [безразм.]")
print(f"  Масштаб длины: λ_L = l_P_SI / l_P_nat = {lambda_len:.6e} м")
print()

# Из c = λ_L/λ_T:
lambda_time = lambda_len / c_SI  # с/натед.времени
c_nat_check = lP_nat / tP_nat
print(f"  c (натур.) = l_P_nat/t_P_nat = {c_nat_check:.6e}  [безразм.]")
print(f"  Масштаб времени: λ_T = λ_L/c_SI = {lambda_time:.6e} с")
print(f"  Проверка: t_P_SI = t_P_nat·λ_T = {tP_nat * lambda_time:.6e} с")
print(f"  t_P (CODATA) = {tP_SI:.6e} с")
print(f"  Ошибка: {abs(tP_nat * lambda_time - tP_SI) / tP_SI * 100:.4f}%")
