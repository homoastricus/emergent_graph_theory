# Форматирование для Markdown
def fmt(val, col):
    if col in ["√2", "√3", "ln K", "ln N", "N^(1/3)"]:
        if val == 0:
            return "0"
        return f"{val:+.0f}" if val == int(val) else f"{val:+.1f}"
    elif col == "π":
        if val == 0:
            return "0"
        return f"{val:+.1f}"
    return str(val)


