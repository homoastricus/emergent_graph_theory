# Проверка: для частиц с одинаковыми (b,c,d) но разными названиями
# (изоспиновые мультиплеты)
multiplets = [
    ('ħ', 'h'),
    ('m_pi_meson',),
    ('m_proton',),
    ('Sigma_plus', 'Sigma_minus'),
    ('Ksi_0', 'Ksi_minus'),
    ('m_z_bozon', 'm_w_bozon'),
]

print(f"   Изоспиновые мультиплеты и их ошибки:")
for mult in multiplets:
    if len(mult) >= 2:
        errors = [df[df['name'] == n]['error_pct'].values[0] for n in mult if n in df['name'].values]
        if len(errors) >= 2:
            spread = max(errors) - min(errors)
            print(f"   {', '.join(mult)}: ошибки={[f'{e:+.4f}%' for e in errors]}, разброс={spread:.4f}%")

# ============================================================
# 9. КОРРЕЛЯЦИЯ ОШИБКИ С ВЕЛИЧИНОЙ КОНСТАНТЫ
# ============================================================
print(f"\n9. ЗАВИСИМОСТЬ ОШИБКИ ОТ ВЕЛИЧИНЫ КОНСТАНТЫ")

# Группируем по порядку величины
df['order'] = np.floor(df['log_mass'])
for order in sorted(df['order'].unique()):
    df_ord = df[df['order'] == order]
    if len(df_ord) >= 2:
        print(f"   Порядок 10^{int(order):>+3}: N={len(df_ord):>2}, ср.ош.={df_ord['error_pct'].mean():>+8.4f}%")

# ============================================================
# 10. ТОП-10 ЛУЧШИХ И ХУДШИХ
# ============================================================
print(f"\n10. ТОП-10 ЛУЧШИХ СОВПАДЕНИЙ")
for _, row in df.nsmallest(10, 'abs_error').iterrows():
    print(
        f"   {row['name']:<25} ошибка={row['error_pct']:>+10.6f}% (a={row['a']}, b={row['b']}, c={row['c']}, d={row['d']}) [{row['category']}]")

print(f"\n11. ТОП-10 ХУДШИХ СОВПАДЕНИЙ")
for _, row in df.nlargest(10, 'abs_error').iterrows():
    print(
        f"   {row['name']:<25} ошибка={row['error_pct']:>+10.6f}% (a={row['a']}, b={row['b']}, c={row['c']}, d={row['d']}) [{row['category']}]")

# ============================================================
# 12. СТАТИСТИЧЕСКИЕ ТЕСТЫ
# ============================================================
