for param in params:
    corr_sign = df['sign'].corr(df[param])
    corr_abs = df['abs_error'].corr(df[param])
    corr_val = df['error_pct'].corr(df[param])
    print(f"   {param}: corr(знак)={corr_sign:+.4f}, corr(|ошибка|)={corr_abs:+.4f}, corr(ошибка)={corr_val:+.4f}")

# Корреляция с логарифмом массы
corr_mass = df['error_pct'].corr(df['log_mass'])
