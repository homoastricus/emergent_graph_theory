# t-тест: значимо ли среднее отличается от нуля?
t_stat, p_val = stats.ttest_1samp(df['error_pct'], 0)
print(f"   t-тест (H0: среднее=0): t={t_stat:.4f}, p={p_val:.6f}")
print(f"   {'✅ Среднее НЕ отличается от нуля' if p_val > 0.05 else '❌ Среднее ЗНАЧИМО отличается от нуля'}")

# Тест Манна-Уитни: различаются ли ошибки для положительных и отрицательных a?
df_pos_a = df[df['a'] > 0]['abs_error']
df_neg_a = df[df['a'] < 0]['abs_error']
if len(df_pos_a) > 0 and len(df_neg_a) > 0:
    mw_stat, mw_p = stats.mannwhitneyu(df_pos_a, df_neg_a)
    print(f"   Манн-Уитни (|ошибка|: a>0 vs a<0): p={mw_p:.6f}")
    print(f"   {'✅ Значимое различие' if mw_p < 0.05 else '❌ Нет значимого различия'}")

# ANOVA: различаются ли ошибки по категориям?
categories = [df[df['category'] == cat]['error_pct'].values for cat in df['category'].unique() if
              len(df[df['category'] == cat]) >= 3]
if len(categories) >= 2:
    f_stat, f_p = stats.f_oneway(*categories)
    print(f"   ANOVA (ошибки по категориям): F={f_stat:.4f}, p={f_p:.6f}")
    print(f"   {'✅ Значимые различия между категориями' if f_p < 0.05 else '❌ Нет значимых различий'}")

# ============================================================
# 13. ВЫВОДЫ
# ============================================================
print(f"\n{'=' * 100}")
print("ВЫВОДЫ")
print(f"{'=' * 100}")

# Собираем ключевые наблюдения
observations = []

# 1. Знак ошибки
if abs(df['error_pct'].mean()) < 0.05:
    observations.append("✅ Средняя ошибка ПРАКТИЧЕСКИ НУЛЕВАЯ — модель несмещена")
elif df['error_pct'].mean() > 0:
    observations.append("⚠️ Модель СИСТЕМАТИЧЕСКИ ЗАВЫШАЕТ значения")
else:
    observations.append("⚠️ Модель СИСТЕМАТИЧЕСКИ ЗАНИЖАЕТ значения")

# 2. Нормальность
if p_sw > 0.05:
    observations.append("✅ Распределение ошибок НОРМАЛЬНОЕ — ожидаемо для хорошо специфицированной модели")
else:
    observations.append("⚠️ Распределение ошибок НЕ нормальное — возможны систематические эффекты")

# 3. Категории
best_cat = df.groupby('category')['abs_error'].mean().idxmin()
worst_cat = df.groupby('category')['abs_error'].mean().idxmax()
observations.append(f"📊 Лучшая категория: {best_cat}, худшая: {worst_cat}")

# 4. Параметры
for param in params:
    corr = df['error_pct'].corr(df[param])
    if abs(corr) > 0.2:
        observations.append(f"📈 Параметр {param} КОРРЕЛИРУЕТ с ошибкой (r={corr:+.3f})")

# 5. Масса
if abs(corr_mass) > 0.2:
    observations.append(f"📈 Ошибка зависит от величины константы (r={corr_mass:+.3f})")

print()
for obs in observations:
    print(f"   {obs}")