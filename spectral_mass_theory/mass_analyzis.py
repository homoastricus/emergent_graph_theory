df['error_cluster'] = pd.cut(df['abs_error'], bins=bins, labels=labels)

for cluster in labels:
    df_cl = df[df['error_cluster'] == cluster]
    if len(df_cl) > 0:
        print(f"   {cluster:<15}: {len(df_cl):>2} частиц — {', '.join(df_cl['name'].values)}")

# ============================================================
