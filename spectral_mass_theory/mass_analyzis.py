# Тест Шапиро-Уилка
stat_sw, p_sw = stats.shapiro(df['error_pct'])
print(f"   Шапиро-Уилк: statistic={stat_sw:.4f}, p-value={p_sw:.6f}")
print(f"   {'✅ Нормальное' if p_sw > 0.05 else '❌ НЕ нормальное'} распределение")

# Тест Колмогорова-Смирнова
stat_ks, p_ks = stats.kstest(df['error_pct'], 'norm', args=(df['error_pct'].mean(), df['error_pct'].std()))
print(f"   Колмогоров-Смирнов: statistic={stat_ks:.4f}, p-value={p_ks:.6f}")

# Асимметрия и эксцесс
skew = stats.skew(df['error_pct'])
kurt = stats.kurtosis(df['error_pct'])
print(f"   Асимметрия: {skew:.4f} (0 = нормальное)")
print(f"   Эксцесс: {kurt:.4f} (0 = нормальное)")

# ============================================================
# 3. КОРРЕЛЯЦИИ С ПАРАМЕТРАМИ
