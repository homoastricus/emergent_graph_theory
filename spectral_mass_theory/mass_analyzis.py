# Создаём DataFrame
df = pd.DataFrame(data, columns=['name', 'a', 'b', 'c', 'd', 'pred', 'exp', 'category'])

# Вычисляем ошибки
df['error_pct'] = (df['pred'] / df['exp'] - 1) * 100
df['abs_error'] = np.abs(df['error_pct'])
df['sign'] = np.sign(df['error_pct'])
df['log_mass'] = np.log10(np.abs(df['exp']))

