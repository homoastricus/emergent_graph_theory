# ============================================================
# ФУНКЦИЯ C_i
# ============================================================
def compute_Ci(gamma, a, b):
    return gamma/lnN + (b/lnK)*lnN - (a/lnK)*lnlnN

# ============================================================
# ОСНОВНОЙ РАСЧЁТ
# ============================================================
Ai_data = []

for name, cat, a, b in all_constants:
    if name not in gamma_measured:
        continue

    gamma = gamma_measured[name]
    Ci = compute_Ci(gamma, a, b)
    Ci_pi = Ci / pi

    # --- определяем n_i ---
    if abs(b) < 1e-6:
        n_i = round(Ci_pi)
        base = n_i
    elif abs(b - 1 / 3) < 1e-6:
        n_i = round(Ci_pi - gamma_E)
        base = n_i + gamma_E
    else:
        continue

    if abs(base) < 1e-10:
        continue

    ratio = Ci / (pi * base)
    delta_i = math.log(ratio)

    Ai_data.append({
        'name': name,
        'category': cat,
        'a': a,
        'b': b,
        'n_i': n_i,
        'Ci': Ci,
        'delta_i': delta_i,
    })

# ============================================================
# δ0
# ============================================================
delta0 = np.mean([x['delta_i'] for x in Ai_data])

# ============================================================
# A_i
# ============================================================
for x in Ai_data:
    x['A_i'] = (x['delta_i'] - delta0) * (lnN**2)

