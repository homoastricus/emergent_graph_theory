# СГРУППИРОВАННАЯ СТАТИСТИКА ПО K^p
# ============================================================
print(f"\n{'=' * 120}")
print("РАСПРЕДЕЛЕНИЕ K^p ПО СПИНАМ")
print(f"{'=' * 120}")

from collections import defaultdict

by_spin = defaultdict(list)
for r in results:
    by_spin[r['spin']].append(r['K_pow'])

print(f"\n  {'Спин':<8} {'N':>4} {'Среднее K^p':>12} {'Мин K^p':>10} {'Макс K^p':>10} {'Диапазон':>15}")
print(f"  {'─' * 65}")
