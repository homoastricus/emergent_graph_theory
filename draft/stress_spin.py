"""
РАСШИРЕННАЯ ТАБЛИЦА ВОЗБУЖДЁННЫХ СОСТОЯНИЙ
Поиск формул для проверки гипотезы K^p ≥ -1 для спина 1

Стратегия:
  1. Для каждого возбуждённого состояния известна масса
  2. Известно, что a=6 для барионов, a=5 для мезонов
  3. Подбираем K^p и π^q, минимизируя ошибку
  4. Проверяем корреляцию K^p со спином
"""

import math
import numpy as np

# ============================================================
# ПАРАМЕТРЫ
# ============================================================
K = 6.0
pi = math.pi
lnN = math.log(4.197668e121)
N13 = (4.197668e121) ** (1 / 3)

# ============================================================
# ВОЗБУЖДЁННЫЕ СОСТОЯНИЯ ДЛЯ ПРОВЕРКИ ГИПОТЕЗЫ
# (name, mass_MeV, a, spin, category)
# ============================================================
