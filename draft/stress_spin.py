print(f"  {'─' * 80}")

for r in sorted(results, key=lambda x: x['spin']):
    status = '✅ K^p≥-1' if r['hypothesis_pass'] else ('❌ K^p<-1' if r['spin'] >= 1 else '— (спин 0)')
    print(
        f"  {r['name']:<14} {r['mass']:>8.0f} {r['a']:>3} {r['spin']:>5.1f} {r['K_pow']:>7.1f} {r['pi_pow']:>7.1f} {r['error']:>10.4f} {status:>12}")

