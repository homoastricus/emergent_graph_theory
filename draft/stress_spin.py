print(f"  Предсказание: все возбуждённые состояния со спином ≥ 1 должны иметь K^p ≥ -1")
print()

results = []
for name, mass_MeV, a, spin, category in excited_states:
    # Перевод МэВ в кг (1 МэВ = 1.78266192e-30 кг)
    mass_kg = mass_MeV * 1.78266192e-30

    p, q, err = find_best_powers(mass_kg, a)

    results.append({
        'name': name, 'mass': mass_MeV, 'a': a, 'spin': spin,
        'K_pow': p, 'pi_pow': q, 'error': err, 'category': category,
        'hypothesis_pass': (spin < 1) or (p >= -1.0),
    })

# ============================================================
