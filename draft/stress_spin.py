spin1_states = [r for r in results if r['spin'] >= 1]
pass_count = sum(1 for r in spin1_states if r['hypothesis_pass'])
fail_count = len(spin1_states) - pass_count

print(f"\n  Всего состояний со спином ≥ 1: {len(spin1_states)}")
print(f"  Прошли гипотезу (K^p ≥ -1):     {pass_count}")
print(f"  НЕ прошли гипотезу (K^p < -1):   {fail_count}")

if fail_count == 0:
    print(f"\n  ✅ ГИПОТЕЗА ПОДТВЕРЖДЕНА!")
    print(f"  Все {len(spin1_states)} состояний со спином ≥ 1 имеют K^p ≥ -1")
else:
    print(f"\n  ❌ ГИПОТЕЗА НАРУШЕНА для {fail_count} состояний:")
    for r in spin1_states:
        if not r['hypothesis_pass']:
            print(f"    {r['name']}: спин={r['spin']}, K^p={r['K_pow']}")

