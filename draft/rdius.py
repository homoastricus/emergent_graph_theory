import math
import numpy as np

# ============================================================
# ФУНДАМЕНТАЛЬНЫЕ ПАРАМЕТРЫ
# ============================================================
K = 6.0
pi = math.pi
lnK = math.log(K)

N = 4.197668e121
lnN = math.log(N)
N13 = N ** (1 / 3)

# ============================================================
# ЭМЕРДЖЕНТНЫЕ ФОРМУЛЫ ДЛЯ ДЛИН
# ============================================================
# Планковская длина (фундаментальный масштаб)
l_P = 4 * lnN ** 2 * lnK / N13

# Боровский радиус (атомный масштаб)
a_0 = K ** (3 / 2) / (8 * pi * lnN ** 4 * lnK)

# Комптоновская длина электрона
lambda_C_e = K ** (3 / 2) * lnK / (2 * pi * lnN ** 5)

# Комптоновская длина протона
lambda_C_p = 2 * K ** (5 / 2) * lnK / (pi ** 0.5 * lnN ** 7)

# ============================================================
# РАДИУС ВСЕЛЕННОЙ ИЗ РАЗНЫХ СООБРАЖЕНИЙ
# ============================================================

# Метод 1: через хаббловский горизонт
# R_H = c / H_0, где c — скорость света (эмерджентная)
c = pi * lnN ** 4 / (K ** 2 * lnK)
H_0 = 2.3e-18  # постоянная Хаббла в с^-1
R_Hubble = c / H_0

# Метод 2: через число узлов графа
# Каждый узел занимает планковский объём ~ l_P^3
# Радиус сферы, содержащей N узлов:
# V = N**3/2
# rd = (3*N**3/2 / 4pi )^0.333
R_graph = (3 * N**(3/2)/ (4 * pi))**(1/3) * l_P

# Метод 3: через космологическую постоянную
# В ЕТИ: Lambda = (ln N)^12 / (sqrt(pi) * N^(2/3))
Lambda = lnN ** 12 / (pi ** 0.5 * N13 ** 2)
# R ~ 1 / sqrt(Lambda) (де-ситтеровский горизонт)
R_Lambda = 1.0 / math.sqrt(abs(Lambda))

# Метод 4: через эйнштейновскую постоянную
# kappa = 128 * K^3 * lnK^3 / (lnN^3 * N^(1/3))
kappa_E = 128 * K ** 3 * lnK ** 3 / (lnN ** 3 * N13)
# R ~ kappa^{-1/2} (размерность:kappa ~ 1/длина^2)
R_kappa = 1.0 / math.sqrt(abs(kappa_E))

# Метод 5: через G (гравитационную постоянную) и полную массу
G = 16 * pi ** 3 * lnN ** 13 / (K ** 5 * lnK * N13)
# Полная масса Вселенной из планковской массы
m_P = K / (pi * 4 * lnN ** 3)
M_total = N * m_P
# Гравитационный радиус
R_G = G * M_total / c ** 2

# Метод 6: масштаб из 1/N^(1/3)
# Естественный масштаб длины в теории
R_scale = N13 * l_P  # совпадает с R_graph

# ============================================================
# ВЫВОД
# ============================================================
print("=" * 100)
print("РАДИУС ВСЕЛЕННОЙ ИЗ ЭМЕРДЖЕНТНЫХ ФОРМУЛ ЕТИ")
print("=" * 100)

print(f"\n  Фундаментальные масштабы:")
print(f"    Планковская длина (l_P):      {l_P:.4e} м")
print(f"    Боровский радиус (a_0):       {a_0:.4e} м")
print(f"    Комптоновская длина e:        {lambda_C_e:.4e} м")
print(f"    Комптоновская длина p:        {lambda_C_p:.4e} м")

print(f"\n  Радиус Вселенной (разные методы):")
print(f"    {'Метод':<35} {'R (м)':<18} {'R (св. лет)':<18}")
print(f"    {'─' * 70}")
print(f"    {'Хаббловский горизонт (c/H₀)':<35} {R_Hubble:<18.4e} {R_Hubble / 9.461e15:<18.4e}")
print(f"    {'Граф (N^(1/3) · l_P)':<35} {R_graph:<18.4e} {R_graph / 9.461e15:<18.4e}")
print(f"    {'Де-ситтеровский (1/√Λ)':<35} {R_Lambda:<18.4e} {R_Lambda / 9.461e15:<18.4e}")
print(f"    {'Эйнштейновский (1/√κ)':<35} {R_kappa:<18.4e} {R_kappa / 9.461e15:<18.4e}")
print(f"    {'Гравитационный (GM/c²)':<35} {R_G:<18.4e} {R_G / 9.461e15:<18.4e}")

print(f"\n  Наблюдаемый радиус Вселенной:     ≈ 4.4 × 10^26 м ≈ 46.5 млрд св. лет")

