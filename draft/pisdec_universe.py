print("\n" + "=" * 100)
print("ОТНОСИТЕЛЬНЫЕ ИЗМЕНЕНИЯ (ОТНОСИТЕЛЬНО СОВРЕМЕННЫХ ЗНАЧЕНИЙ)")
print("=" * 100)

