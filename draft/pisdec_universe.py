"""
Моделирование эволюции фундаментальных констант ГИП при изменении N
N = число узлов графа (информационная емкость Вселенной)
N растет со временем (от ранней Вселенной до современной)
"""

import math
import numpy as np
import matplotlib.pyplot as plt

# =========================================================
# ФОРМУЛЫ ГИП (финальная согласованная версия)
# =========================================================

K = 6.0
pi = math.pi
e = math.e

def compute_constants(N):
    """Вычисляет все фундаментальные константы для заданного N"""
    if N <= 1:
        N = 1.0
    lnN = math.log(N)
    if lnN == 0:
        lnN = 1e-10  # защита от нуля
    N13 = N ** (1/3)

    constants = {
        'ħ': (lnN ** 3) / (K * N13),
        'h': 2 * pi * (lnN ** 3) / (K * N13),
        't_P': pi / (K * N13 * lnN),
        'E_P': (lnN ** 4) / pi,
        'c': pi * (lnN ** 4) / (K ** 2 * math.log(K)),
        'l_P': pi ** 2 * (lnN ** 3) / (K ** 3 * math.log(K) * N13),
    }
    return constants

# =========================================================
# ЭВОЛЮЦИЯ N (логарифмическая шкала)
# =========================================================

# Создаем массив N: от 10^1 до 10^140 с шагом ~0.15 в степени (чтобы 40 шагов)
exponents = np.linspace(1, 140, 40)
N_values = 10 ** exponents

# Массивы для хранения значений констант
const_names = ['ħ', 'h', 't_P', 'E_P', 'c', 'l_P']
const_data = {name: [] for name in const_names}
lnN_values = []
N13_values = []

# Нормализация к современным значениям
modern_N = 4.179e121
modern_const = compute_constants(modern_N)

# Сбор данных
for N in N_values:
    const = compute_constants(N)
    lnN = math.log(N)
    for name in const_names:
        const_data[name].append(const[name])
    lnN_values.append(lnN)
    N13_values.append(N ** (1/3))

# =========================================================
# ВИЗУАЛИЗАЦИЯ
# =========================================================

fig, axes = plt.subplots(2, 3, figsize=(15, 10))
axes = axes.flatten()

colors = ['blue', 'cyan', 'green', 'orange', 'red', 'purple']

for i, name in enumerate(const_names):
    ax = axes[i]
    values = const_data[name]
    modern_val = modern_const[name]

    # Относительное изменение относительно современного значения
    relative = [v / modern_val for v in values]

    ax.semilogx(N_values, relative, color=colors[i], linewidth=2)
    ax.axhline(y=1.0, color='black', linestyle='--', alpha=0.5, label='Современное значение')
    ax.axvline(x=modern_N, color='red', linestyle='--', alpha=0.5, label='Современная Вселенная')

    ax.set_xlabel('N (число узлов, информационная емкость)', fontsize=10)
    ax.set_ylabel(f'{name} / современное значение', fontsize=10)
    ax.set_title(f'{name} (современное: {modern_val:.3e})', fontsize=12)
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)

plt.tight_layout()
plt.savefig('constants_evolution.png', dpi=150)
plt.show()

