def t_P(N):
    """Планковское время (один тик)"""
    if N <= 1:
        return float('inf')
    return pi / (K * N ** (1 / 3) * math.log(N))


def N_dot(N):
    """
    ЕДИНСТВЕННАЯ самосогласованная скорость роста N.
    Вывод:
      S = ln N (энтропия)
      S ~ R² (голография) → R ~ √(ln N)
      a³ ~ N → a ~ N^(1/3)
      H = ȧ/a = (1/3)Ṅ/N
      H ~ 1/R ~ 1/√(ln N) (причинный горизонт)
      ⇒ Ṅ = 3N/√(ln N)
    """
    if N <= 1:
        return 0.0
    return 3 * N / math.sqrt(math.log(N))


def H(N):
    """Параметр Хаббла H = ȧ/a"""
    if N <= 1:
        return 0.0
    return 1.0 / math.sqrt(math.log(N))


def scale_factor(N):
    """Масштабный фактор a ~ N^(1/3)"""
    return N ** (1 / 3)


def physical_time(N_max, N_min=2, num_points=20000):
    """
    Физическое время: t(N) = ∫ dN/Ṅ = ∫ √(ln N)/(3N) dN
    Аналитически: t(N) = (2/9) · (ln N)^(3/2) + const
    """
    if N_max <= N_min:
        return 0.0

    # Логарифмическая сетка для точности
    ln_vals = np.linspace(math.log(N_min), math.log(N_max), num_points)
    N_vals = np.exp(ln_vals)

    # Подынтегральная функция: 1/Ṅ = √(ln N)/(3N)
    integrand = np.sqrt(np.log(N_vals)) / (3 * N_vals)

    # Интегрирование
    t_vals = cumulative_trapezoid(integrand, N_vals, initial=0)

    return t_vals[-1]


def physical_time_analytic(N):
    """Аналитическая формула: t(N) = (2/9) · (ln N)^(3/2)"""
    return (2.0 / 9.0) * math.log(N) ** (3 / 2)


def rho_eff(N):
    """Эффективная плотность энергии: ρ_eff ~ 1/ln a ~ 1/ln(N^(1/3))"""
    if N <= 1:
        return float('inf')
    return 1.0 / math.log(N ** (1 / 3))


def equation_of_state(N):
    """Параметр уравнения состояния w = p/ρ"""
    # Для ρ ~ 1/ln a: w = -1 + 2/(3 ln a)
    ln_a = math.log(N ** (1 / 3))
    if ln_a <= 0:
        return -1.0
    return -1.0 + 2.0 / (3.0 * ln_a)


