"""
КОД ДЛЯ RG-АНАЛИЗА И ПОИСКА МАТЕМАТИЧЕСКИХ ЗАКОНОМЕРНОСТЕЙ
В ПАРАМЕТРАХ ГРАФА МАЛОГО МИРА (SMALL-WORLD)

Вычисляет:
- RG-инвариант c = p * N^(1/d) / (ln N)^(1/3)
"""

import math

def compute_c(p, N, d=3):
    """
    Вычисляет RG-инвариант c = p * N^(1/d) / (ln N)^(1/3)

    Параметры:
        p : float - вероятность дальних связей
        N : float - число узлов графа
        d : int - размерность (по умолчанию 3)
    Возвращает:
        c : float - RG-инвариант
    """
    lnN = math.log(N)
    # Защита от деления на ноль
    if lnN <= 0:
        return float('nan')
    x = p * (N ** (1.0 / d))
    c = x / (lnN ** (1.0 / 3.0))
    return c


def main():
    print("RG-АНАЛИЗ И ПОИСК МАТЕМАТИЧЕСКИХ ЗАКОНОМЕРНОСТЕЙ")
    print("ПАРАМЕТРЫ ГРАФА МАЛОГО МИРА (SMALL-WORLD)")

    # ===== ВАШИ ПАРАМЕТРЫ (из модели ПНИД) =====
    # Здесь нужно подставить реальные значения из вашей оптимизации!
    K_opt = 4     # оптимальная локальная связность (из ПНИД)
    p_opt = 4.141560e-40  # вероятность дальних связей (из ПНИД)
    N_opt = 1e122      # число узлов (голографическая энтропия)
    d = 3              # размерность пространства

    print("\n📊 ОПТИМАЛЬНЫЕ ПАРАМЕТРЫ (из ПНИД):")
    print(f"  K = {K_opt:.4f}")
    print(f"  p = {p_opt:.4e}")
    print(f"  N = {N_opt:.1e}")
    print(f"  d = {d}")

    # Вычисление RG-инварианта c
    c_opt = compute_c(p_opt, N_opt, d)
    print(f"\n🔢 RG-ИНВАРИАНТ c = p * N^(1/d) / (ln N)^(1/3):")
    print(f"  c = {c_opt:.6f}")


if __name__ == "__main__":
    main()