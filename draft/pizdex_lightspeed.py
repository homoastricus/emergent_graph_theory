UNIVERSAL_TOKENS = sorted(set(ALL_TOKENS))


def formula_to_vector(formula_str: str) -> list:
    """Преобразует формулу в вектор степеней"""
    powers = parse_to_powers(formula_str)
    return build_power_vector(powers, UNIVERSAL_TOKENS)


