# 2. ФУНКЦИЯ ПАРСИНГА ФОРМУЛЫ В СЛОВАРЬ СТЕПЕНЕЙ
# ------------------------------------------------------------
def parse_to_powers(formula_str: str) -> dict:
    """
    Преобразует строку формулы в словарь {токен: степень}.
    Например: "lnK / (lnN)^5" -> {'lnK': 1, 'lnN': -5}
    """
    powers = defaultdict(float)

    # Нормализация строки
    s = formula_str.strip()
    s = s.replace(' ', '')  # убираем все пробелы
    s = s.replace('²', '^2')  # верхние индексы
    s = s.replace('³', '^3')
    s = s.replace('π', 'pi')  # унифицируем π
    s = s.replace('e^pi', 'e_pow_pi')  # специальный токен e^π
    s = s.replace('e**pi', 'e_pow_pi')
    s = s.replace('√', 'sqrt')  # корни
    s = s.replace('**(-', '^(m')  # отрицательные степени: )^(- -> )^(m
    # восстанавливаем e^π если было e_pow_pi
    s = s.replace('e_pow_pi', 'e^pi')

    # Разбиваем на токены, разделённые операторами *, /, (, )
    # Сначала добавляем пробелы вокруг операторов
    s = re.sub(r'([*/()])', r' \1 ', s)
    s = re.sub(r'\^', ' ^ ', s)

    tokens = s.split()

    # Проходим по токенам и вычисляем степени
    current_sign = 1  # 1 для числителя, -1 для знаменателя
    current_power = 1
    stack = []  # стек для скобок

    i = 0
    while i < len(tokens):
        token = tokens[i]

        if token == '(':
            stack.append((current_sign, current_power))
            i += 1
            continue
        elif token == ')':
            if stack:
                current_sign, current_power = stack.pop()
            i += 1
            continue
        elif token == '*':
            current_power = 1
            i += 1
            continue
        elif token == '/':
            current_sign = -1
            current_power = 1
            i += 1
            continue
        elif token == '^':
            # следующий токен — степень
            if i + 1 < len(tokens):
                power_str = tokens[i + 1]
                # обрабатываем отрицательные степени m5 -> -5
                if power_str.startswith('(') and power_str.endswith(')'):
                    power_str = power_str[1:-1]
                if power_str.startswith('m'):
                    current_power = -int(power_str[1:])
                else:
                    try:
                        current_power = int(power_str)
                    except ValueError:
                        try:
                            current_power = float(power_str)
                        except ValueError:
                            current_power = 1
                i += 2
                continue
            else:
                i += 1
                continue
        else:
            # Это токен-сущность (константа или переменная)
            # Проверяем, не является ли это числом
            try:
                float(token)
                i += 1
                continue  # числа игнорируем в аналитической проверке
            except ValueError:
                pass

            # Ищем совпадение с известными токенами
            matched = False
            for known_token in ALL_TOKENS:
                if token == known_token or token.startswith(known_token):
                    powers[known_token] += current_sign * current_power
                    matched = True
                    break

            if not matched:
                # пробуем найти токен внутри
                for known_token in ALL_TOKENS:
                    if known_token in token:
                        powers[known_token] += current_sign * current_power
                        matched = True
                        break

            if not matched:
                print(f"  Предупреждение: нераспознанный токен '{token}' в формуле: {formula_str}")

            current_power = 1
            i += 1

    return dict(powers)


# ------------------------------------------------------------
# 3. ФУНКЦИЯ ИЗВЛЕЧЕНИЯ ФОРМУЛ ИЗ ТЕКСТА
# ------------------------------------------------------------
def extract_formulas(text: str) -> list:
    """Извлекает список формул с метками ε/μ из текста"""
    formulas = []
    current_target = None

    for line in text.strip().split('\n'):
        line = line.strip()
        if not line:
            continue

        if 'Цель: ε₀' in line:
            current_target = 'epsilon'
            continue
        elif 'Цель: μ0' in line:
            current_target = 'mu'
            continue

        # Извлекаем формулу
        match = re.match(r'^\s*\d+\.\s+(.+?)(?:\s{2,}Значение:|$)', line)
        if match:
            formula_str = match.group(1).strip()
            # Убираем звёздочки
            formula_str = re.sub(r'\s*⭐+$', '', formula_str).strip()

            if formula_str and current_target:
                formulas.append({
                    'target': current_target,
                    'formula': formula_str
                })

    return formulas


# ------------------------------------------------------------
# 4. ПОСТРОЕНИЕ ВЕКТОРОВ СТЕПЕНЕЙ
# ------------------------------------------------------------
def build_power_vector(powers: dict, all_tokens: list) -> list:
    """Строит вектор степеней в порядке all_tokens"""
    return [powers.get(token, 0) for token in all_tokens]


