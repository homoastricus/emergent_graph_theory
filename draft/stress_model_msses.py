# Функция вычисления по степеням
def compute_mass(a_lnN, a_sqrt2, a_sqrt3, a_pi, with_exp=False, gamma=0):
    M = (lnN ** a_lnN) * (N ** (-1 / 3))
    M *= (sqrt2 ** a_sqrt2)
    M *= (sqrt3 ** a_sqrt3)
    M *= (pi ** a_pi)
    if with_exp:
        M *= math.exp(gamma * math.log(6) / lnN)
    return M


