# ВЫЧИСЛЕНИЕ ПОЛНОЙ ФОРМУЛЫ
# ============================================================
def compute_mass(a, b, q, alpha, beta, C_tilde, gamma_i):
    """
    Полная формула ЕТИ:
    M = C_tilde * (lnN)^a * N^(-b) * pi^q * 2^alpha * 3^beta * exp(gamma_i * lnK / lnN)

    После редукции K = 2·3:
    M = C_tilde * (lnN)^a * N^(-b) * pi^q * 2^(alpha + p) * 3^(beta + p)
    где p — исходная степень K.

    Но здесь мы используем УЖЕ редуцированные индексы,
    где alpha и beta включают вклад от K.
    """
    # Ведущий порядок
    M0 = C_tilde * (lnN ** a) * (N ** (-b)) * (pi ** q)

    # Множители 2 и 3 (редуцированные)
    if alpha != 0:
        M0 *= (2 ** alpha)
    if beta != 0:
        M0 *= (3 ** beta)

    # Тонкая поправка
    M = M0 * math.exp(gamma_i * correction_scale)

    return M, M0


