# Более реалистично: для логарифмической шкалы
# 1% точность по массе = 0.01 по ln M
# Каждый параметр вносит вклад в ln M через умножение на ln(pi), ln(sqrt2), ln(sqrt3)
# Погрешность в параметре d на 1 даёт погрешность в ln M на ln(pi) ≈ 1.14
# Значит, точность 0.01 по ln M требует точности параметра ~0.01

# Оценим число "близких" комбинаций
# d: шаг 0.5, допуск 0.01 -> только 1 значение (ближайшее)
# c: значения разнесены на единицы -> только 1
# b: аналогично -> только 1
# a: всего 3 значения, влияет через ln(ln N) ≈ 5.6 -> разница в a на 1 даёт
#    разницу в ln M на ln(ln N) ≈ 5.6, что огромно -> только 1 значение

