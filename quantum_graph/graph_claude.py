print("""
ГИПОТЕЗА B: КОНЕЧНО-РАЗМЕРНЫЙ ЭФФЕКТ НЕЛОКАЛЬНЫХ СВЯЗЕЙ

Нелокальных связей: p_nl × N² / 2 ≈ N^(5/3)/(2K)

Для L=7 (N=343): ~343^(5/3)/(12) ≈ 1000/12 ≈ 83 нелокальных связей
Для L=8 (N=512): ~512^(5/3)/(12) ≈ 1365/12 ≈ 114 нелокальных связей

При случайных фазах 0..2π на каждой связи:
Среднее поле = 0 (фазы усредняются).
Когда нелокальных связей много — они "глушат" щель!
""")

K = 6
pi = math.pi
print("Число нелокальных связей для каждого L:")
for L, N, lnN, Delta, lam0, C in data:
    p_nl = 1/(K*N**(1/3))
    n_nl = p_nl * N  # среднее число нелокальных связей
    print(f"  L={L:2d}: p_nl={p_nl:.5f}, ожид. нелок. = {n_nl:.1f}")

print("""
ВЫВОД: При L=7→8 число нелокальных связей переходит порог,
при котором их случайные фазы начинают "глушить" спектральную щель.
""")

print("=" * 65)
print("ДИАГНОЗ 2: λ₀ < 0 — СЕРЬЁЗНАЯ ПРОБЛЕМА")
print("=" * 65)

print("""
Для всех L: λ₀ < 0!

  L= 3: λ₀ = -1.314
  L= 8: λ₀ = -0.202
  L=16: λ₀ = -0.027

Лапласиан L = D - A должен быть ПОЛОЖИТЕЛЬНО ПОЛУОПРЕДЕЛЁННЫМ.
Все собственные значения должны быть ≥ 0.

Отрицательные λ₀ означают, что матрица H НЕ является правильным
лапласианом. Это артефакт фазовой матрицы e^{iθ}.

При комплексных весах A_{ij} = e^{iθ_{ij}}:
  D_{ii} = Σ_j |A_{ij}| = степень узла (вещественная)
  L = D - A  ← несимметрична по вещественной части!

Вещественная часть Re(L) может иметь отрицательные собственные значения.
""")

print("Масштаб λ₀ убывает с N:")
for L, N, lnN, Delta, lam0, C in data:
    print(f"  L={L:2d}, N={N:4d}: λ₀={lam0:+.4f}, |λ₀|/lnN = {abs(lam0)/lnN:.4f}")

print("""
|λ₀| ~ 1/N^{α} с показателем α > 0 — λ₀ → 0 при N → ∞.

Это указывает: при больших N матрица становится "почти корректной".
Проблема — конечно-размерный артефакт.
""")

print("=" * 65)
print("ДИАГНОЗ 3: ЧТО РЕАЛЬНО ИЗМЕРЯЕТСЯ КАК Δ?")
print("=" * 65)

print("""
Δ = λ₁ - λ₀ при λ₀ < 0 — это разность первых двух собственных значений.

Но физически щель должна измеряться как:
  (a) λ₁ - λ₀  (разность первых двух уровней)
  (b) λ_gap = min λ > 0  (первый положительный уровень)

При λ₀ < 0 вариант (a) может быть случайным.

Нужно перейти к варианту (b): найти минимальное ПОЛОЖИТЕЛЬНОЕ
собственное значение. Это и есть настоящая "щель" в спектре.
""")

# Переоцениваем C = Δ·lnN с учётом λ₀
print("\nПри больших N (L=8..16), Δ → 0:")
for L, N, lnN, Delta, lam0, C in data[5:]:
    print(f"  L={L:2d}: Δ={Delta:.6f} → C=Δ·lnN={C:.4f}")

print("""
Δ убывает быстрее, чем 1/lnN. Это означает:
  Если гипотеза Δ ~ 1/lnN, то при lnN→280:
  Δ(ETI) = C(280)/lnN_ETI

  Но C сам убывает с N — какая зависимость C(N)?
""")

# Фитируем C(N) = A / N^beta
lnN_arr = np.array([d[2] for d in data[5:]])  # большие N (L=8..16)
C_arr   = np.array([d[5] for d in data[5:]])

# Логарифмический фит: ln C = a + b·lnN
log_lnN = np.log(lnN_arr)
log_C   = np.log(C_arr)
coeffs  = np.polyfit(log_lnN, log_C, 1)
beta, log_A = coeffs
A = math.exp(log_A)

print(f"\nФит C(lnN) = A / lnN^β при L=8..16:")
print(f"  β = {-beta:.4f}")
print(f"  A = {A:.4f}")
print(f"  C(lnN) = {A:.4f} / lnN^{-beta:.4f}")

# Предсказание для lnN=280
lnN_eti = 280.045
C_eti = A * lnN_eti**beta  # beta < 0 → lnN^beta убывает
Delta_eti = C_eti / lnN_eti
print(f"\n  При lnN_ETI = {lnN_eti}:")
print(f"  C_ETI = {C_eti:.8e}")
print(f"  Δ_ETI = C/lnN = {Delta_eti:.8e}")

