print("""
Для чистого лапласиана Z³ с нелокальными связями:
  A_{ij} = 1  (вещественная, без фаз)

Спектр известен аналитически:
  λ_k = 2K - 2(cos k_x + cos k_y + cos k_z) + p·N·δ_{k≠0}

Минимальное ненулевое значение (спектральная щель):
  Δ = 2K(1 - cos(2π/L)) + p_nl·N

  При малом k=2π/L:
  Δ ≈ K(2π/L)² + N^{2/3}/K
    = K·4π²/N^{2/3} + N^{2/3}/K

  Минимум по N:
  dΔ/dN^{2/3} = 0 → N^{2/3} = K·2π·√K
  
  При N = L³ это дает характерный масштаб.
  
Для L=10 (N=1000):
""")

L_test = 10
N_test = L_test**3
p_nl_test = 1/(K*N_test**(1/3))

# Аналитическая щель чистого лапласиана
k_min = 2*pi/L_test
delta_local = K * 2*(1-math.cos(k_min))
delta_nonlocal = p_nl_test * N_test  # = N^{2/3}/K
delta_total = delta_local + delta_nonlocal

print(f"  p_nl = {p_nl_test:.5f}")
print(f"  Δ_local = 2K(1-cos(2π/L)) = {delta_local:.4f}")
print(f"  Δ_nonlocal = p·N = N^(2/3)/K = {delta_nonlocal:.4f}")
print(f"  Δ_total = {delta_total:.4f}")
print(f"  1/lnN = {1/math.log(N_test):.4f}")
print(f"  Отношение Δ_total/(1/lnN) = {delta_total/(1/math.log(N_test)):.4f}")

print("""
ЧТО ОЗНАЧАЕТ: для ЧИСТОГО (без фаз) лапласиана щель
определяется конкуренцией:
  - Локальных связей: Δ ~ K·(2π/L)² ~ 1/N^{2/3}  (убывает)
  - Нелокальных связей: Δ ~ N^{2/3}/K  (РАСТЁТ с N!)

Суммарная щель имеет минимум при некотором N_min.
Для больших N доминирует нелокальный вклад N^{2/3}/K.

ЭТО СОВСЕМ ДРУГОЕ, чем 1/lnN!
""")

print("=" * 65)
